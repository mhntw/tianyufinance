def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--file", default="index.html")
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()

    with open(args.file, "r", encoding="utf-8") as f:
        src = f.read()
    out = src

    n_rewrite = 0
    for old, new in REWRITE:
        if old in out:
            out = out.replace(old, new)
            n_rewrite += 1

    n_del = 0
    for frag in DELETE_FULL:
        # 删除注释本身，并把该行残留的空白一并收掉
        if frag in out:
            out = out.replace(frag, "")
            n_del += 1

    # 清理：因删除注释产生的空行 / 行尾空白
    lines = out.split("\n")
    cleaned = []
    prev_blank = False
    for ln in lines:
        stripped = ln.rstrip()
        if stripped.strip() == "":
            # 连续空行合并为一个
            if prev_blank:
                continue
            prev_blank = True
        else:
            prev_blank = False
        cleaned.append(stripped)
    out = "\n".join(cleaned)

    before = len(re.findall("<!--", src))
    after = len(re.findall("<!--", out))
    print(f"改写 {n_rewrite} 处，删除 {n_del} 处")
    print(f"HTML 注释：{before} → {after}")

    if args.apply:
        with open(args.file, "w", encoding="utf-8") as f:
            f.write(out)
        print("已写入")
    else:
        print("（dry-run，加 --apply 写入）")


if __name__ == "__main__":
    sys.exit(main())
