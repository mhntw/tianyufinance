'use strict';
/* 布局单点：窗口**安全最小尺寸** + 抽查档位（layout_probe.js 与 check_window_min.js 共用）
 *
 * 【900×600 怎么来的】2026-10-04 用真实渲染实测的边界，不是估的：
 *     1024x640 ✓ 通过      900x600 ✓ 通过      820x600 ✗ 12 项     760x600 ✗ 12 项
 *   820/760 下顶栏中间列被挤到塌陷，期间文本/账号块被推到窗口左缘之外（左缘为负）——
 *   属"看不到"的真缺陷。故取**已证明通过的最窄档 900 作为窗口最小宽度**，
 *   让用户根本缩不到坏的那一段（这是比"事后修补布局"更省事、且不会引入新观感变化的做法）。
 *   高度 600 同理：全档位抽查都在 600 高下通过。
 *
 * ⚠ 想调小它之前，请先跑 node tools/layout_probe.js --sizes=<想要的尺寸> 拿到实测证据，
 *   再同时改本文件与 tauri/src-tauri/tauri.conf.json —— tools/check_window_min.js 会守住两者一致。
 */
module.exports = {
  /* 窗口最小尺寸（tauri.conf.json 的 app.windows[0].minWidth / minHeight 必须 ≥ 这两个值） */
  SAFE_MIN: { w: 900, h: 600 },
  /* 抽查档位：**不得低于 SAFE_MIN**（低于它的尺寸在真机上无法达到，测了也没有意义） */
  SIZES: [[1280, 800], [1024, 640], [900, 600]],
};
